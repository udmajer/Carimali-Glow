const ogLocales = {
  en: "en_US",
  it: "it_IT",
  de: "de_DE",
  es: "es_ES"
};

function replaceAllText(html, dictionary) {
  const keys = Object.keys(dictionary).sort((left, right) => right.length - left.length);
  if (!keys.length) return html;
  const pattern = new RegExp(keys.map((key) => key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|"), "g");
  return html.replace(pattern, (english) => dictionary[english]);
}

function localize(locale) {
  const route = `/${locale}/glow/`;
  let html = source;

  html = html.replace('<html lang="en">', `<html lang="${locale}">`);
  html = html.replace(
    '<meta property="og:locale" content="en_US">',
    `<meta property="og:locale" content="${ogLocales[locale]}">`
  );
  html = html.replace(
    '<meta property="og:url" content="https://carimali-glow.vercel.app/en/glow/">',
    `<meta property="og:url" content="${siteOrigin}${route}">`
  );
  html = html.replace(
    '<link rel="canonical" href="https://carimali-glow.vercel.app/en/glow/">',
    `<link rel="canonical" href="${siteOrigin}${route}">`
  );
  html = html.replace(
    `<option value="${route}">`,
    `<option value="${route}" selected>`
  );

  const formValues = [];
  html = html.replace(/\svalue="[^"]*"/g, (attribute) => {
    const token = ` __GLOW_FORM_VALUE_${formValues.length}__`;
    formValues.push(attribute);
    return token;
  });
  html = replaceAllText(html, translations[locale]);
  html = html.replace(/ __GLOW_FORM_VALUE_(\d+)__/g, (_, index) => formValues[Number(index)]);
  html = html
    .replaceAll('content="assets/', `content="${siteOrigin}/assets/`)
    .replaceAll('href="assets/', 'href="/assets/')
    .replaceAll('src="assets/', 'src="/assets/')
    .replaceAll('srcset="assets/', 'srcset="/assets/')
    .replace('href="scrollcraft.css"', 'href="/scrollcraft.css"')
    .replace('href="styles.css"', 'href="/styles.css"')
    .replace('src="scrollcraft.js"', 'src="/scrollcraft.js"')
    .replace('src="site.js"', 'src="/site.js"');

  return html;
}

